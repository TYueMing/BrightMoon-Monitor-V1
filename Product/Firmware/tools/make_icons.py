"""Build small circular RGB565+A icons from SOLO's trusted source assets."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageOps

ROOT = Path(__file__).resolve().parents[3]
FIRMWARE = Path(__file__).resolve().parents[1] / 'ESP32-S3-Island'
ICONS = {'codex': 'Codex_logo.png', 'claude': 'claude_logo.png', 'opencode': 'Opencode_logo.png',
         'deepseek_harness': 'Deepseek_logo.png', 'solo_task': 'LOGO_EXE.png', 'unknown': 'LOGO.png'}


def main():
    code = ['/* Generated by ../tools/make_icons.py; LV_COLOR_DEPTH=16, LV_COLOR_16_SWAP=1. */',
            '#include "island_icons.h"', '#include <string.h>']
    for name, filename in ICONS.items():
        with Image.open(ROOT/'monitor'/'icon_asset'/filename) as original:
            source = ImageOps.contain(original.convert('RGBA'), (32, 32), Image.Resampling.LANCZOS)
        image = Image.new('RGBA', (36, 36), 'white')
        image.alpha_composite(source, ((36-source.width)//2, (36-source.height)//2))
        mask = Image.new('L', (144, 144)); ImageDraw.Draw(mask).ellipse((0, 0, 143, 143), fill=255)
        image.putalpha(mask.resize((36, 36), Image.Resampling.LANCZOS))
        data = []
        for r, g, b, a in image.getdata():
            rgb = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            data.extend((rgb >> 8, rgb & 255, a))
        code.append('static const uint8_t pixels_'+name+'[] = {\n'+',\n'.join(','.join(str(v) for v in data[i:i+36]) for i in range(0, len(data), 36))+'\n};')
        code.append('static const lv_img_dsc_t icon_'+name+' = {.header={.cf=LV_IMG_CF_TRUE_COLOR_ALPHA,.always_zero=0,.reserved=0,.w=36,.h=36}, .data_size=3888, .data=pixels_'+name+'};')
    code.append('const lv_img_dsc_t *island_icon(const char *app) {')
    for name in ICONS:
        code.append('  if (app && strcmp(app, "'+name+'") == 0) return &icon_'+name+';')
    code.append('  return &icon_unknown;\n}')
    (FIRMWARE/'island_icons.c').write_text('\n'.join(code)+'\n', encoding='utf8')


if __name__ == '__main__': main()
